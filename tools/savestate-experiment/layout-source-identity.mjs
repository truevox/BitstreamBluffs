import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../../',import.meta.url));
const files=[
 ...['candidateAdmission','candidateState','entityState','envelope','matterState','primitiveState',
 'recorderState','RunSceneRestoreKit','sceneRemainderState','sceneSubsystemState','sectionBindings','terrainState',
 'layout','localSuspendSlot','suspendTransaction'].map(x=>'src/systems/savestate/'+x+'.js'),
 'tools/savestate-experiment/matter-snapshot-kit.js',
].sort();
const rows=files.map(path=>[path,'sha256:'+createHash('sha256').update(fs.readFileSync(root+path,'utf8').replace(/\r\n/g,'\n')).digest('hex')]);
const out='// Generated by tools/savestate-experiment/layout-source-identity.mjs; do not edit.\nexport const SAVESTATE_SCHEMA_SOURCES = '+JSON.stringify(rows,null,2)+';\n';
const dest=root+'src/systems/savestate/layoutSources.js';
if(process.argv.includes('--write'))fs.writeFileSync(dest,out);
else if(fs.readFileSync(dest,'utf8')!==out)throw Error('stale savestate schema source identity; regenerate with --write');
else console.log('savestate schema source identity current');
